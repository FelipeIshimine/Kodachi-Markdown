using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace KodachiGames.Markdown.Editor.Reference
{
    public sealed class ReferencePageWriter
    {
        private readonly IReadOnlyDictionary<Type, ReferenceType> _pages;
        private readonly IReadOnlyDictionary<Type, IReadOnlyList<ReferenceType>> _derived;

        public ReferencePageWriter(IReadOnlyDictionary<Type, ReferenceType> pages, IReadOnlyDictionary<Type, IReadOnlyList<ReferenceType>> derived)
        {
            _pages = pages;
            _derived = derived;
        }

        public string Index(ReferencePackage package)
        {
            StringBuilder page = new();
            page.Append("# API reference\n\n");
            page.Append($"← [{package.DisplayName}](../../README.md){GuideLink(package, "../../")}\n\n");
            page.Append("> Every public type in the package, one line each. Each name opens a page with the type's\n");
            page.Append("> declaration, members and related types.\n\n");
            page.Append("## Contents\n\n");
            foreach (ReferenceAssembly assembly in package.Assemblies)
                page.Append($"- [{assembly.Summaries.AssemblyName}](#{Slug(assembly.Summaries.AssemblyName)})\n");
            page.Append("\nThe pages are generated by **Kodachi ▸ Generate API Reference** from the compiled assemblies.\n");
            page.Append("The one-line summaries are written by hand in the `Summaries/` folder, one file per assembly;\n");
            page.Append("edit those, never the pages.\n");

            foreach (ReferenceAssembly assembly in package.Assemblies)
            {
                page.Append($"\n## {assembly.Summaries.AssemblyName}\n\n");
                page.Append($"{assembly.Summaries.AssemblySummary} Summaries: [{assembly.Summaries.AssemblyName}.md](Summaries/{assembly.Summaries.AssemblyName}.md).\n\n");
                page.Append("| Type | Kind | Summary |\n|---|---|---|\n");
                foreach (ReferenceType type in assembly.Types)
                    page.Append($"| {Link(package.Folder, type)} | {Signatures.KindOf(type.Type)} | {Cell(type.Summary)} |\n");
            }

            return page.ToString();
        }

        public string Page(ReferencePackage package, ReferenceType type)
        {
            string folder = Path.GetDirectoryName(type.PagePath);
            StringBuilder page = new();
            page.Append($"# {Title(type.Key)}\n\n");
            page.Append($"← [API reference](README.md#{Slug(type.AssemblyName)}){GuideLink(package, "../../")}\n\n");
            page.Append($"> {type.Summary}\n\n");

            List<string> facts = new()
            {
                $"**Kind:** {Signatures.KindOf(type.Type)}",
                $"**Assembly:** `{type.AssemblyName}`",
                $"**Namespace:** `{type.Type.Namespace}`",
            };
            if (type.Type.IsNested)
                facts.Add($"**Nested in:** {TypeLink(folder, type.Type.DeclaringType)}");
            page.Append(string.Join(" · ", facts)).Append("\n\n");

            List<string> lineage = new();
            Type baseType = Signatures.BaseOf(type.Type);
            if (baseType != null)
                lineage.Add($"**Inherits:** {TypeLink(folder, baseType)}");
            Type[] interfaces = typeof(Delegate).IsAssignableFrom(type.Type) ? Type.EmptyTypes : Signatures.DirectInterfaces(type.Type);
            if (interfaces.Length > 0)
                lineage.Add($"**Implements:** {string.Join(", ", interfaces.Select(i => TypeLink(folder, i)))}");
            if (lineage.Count > 0)
                page.Append(string.Join(" · ", lineage)).Append("\n\n");

            page.Append("```csharp\n").Append(Signatures.Declaration(type.Type)).Append("\n```\n");

            Section(page, "Values", type.EnumValues().Select(Signatures.EnumValue));
            Section(page, "Inspector fields", type.InspectorFields());
            Section(page, "Constructors", type.Constructors().Select(c => Signatures.Constructor(c, Signatures.AccessOf(c))));
            Section(page, "Properties", type.Properties().Select(p => Signatures.Property(p, Signatures.AccessOf(p))));
            Section(page, "Methods", type.Methods().Select(m => Signatures.Method(m, Signatures.AccessOf(m))));
            Section(page, "Events", type.Events().Select(e => Signatures.Event(e, Signatures.AccessOf(e))));
            Section(page, "Fields", type.Fields().Select(f => Signatures.Field(f, Signatures.AccessOf(f))));

            TypeTable(page, "Nested types", folder, _pages.Values
                .Where(t => t.Type.DeclaringType == type.Type)
                .OrderBy(t => t.Key, StringComparer.Ordinal));
            TypeTable(page, type.Type.IsInterface ? "Implemented by" : "Derived types", folder,
                _derived.TryGetValue(type.Type, out IReadOnlyList<ReferenceType> derived) ? derived : Array.Empty<ReferenceType>());

            HashSet<Type> shown = new(interfaces.Select(Definition)) { type.Type };
            if (baseType != null)
                shown.Add(Definition(baseType));
            string[] uses = type.MentionedTypes()
                .Where(t => !shown.Contains(t) && _pages.ContainsKey(t))
                .Select(t => _pages[t])
                .OrderBy(t => t.Key, StringComparer.Ordinal)
                .Select(t => Link(folder, t))
                .ToArray();
            if (uses.Length > 0)
                page.Append("\n## Uses\n\n").Append(string.Join(" · ", uses)).Append('\n');

            return page.ToString();
        }

        private static void Section(StringBuilder page, string heading, IEnumerable<string> lines)
        {
            string[] all = lines.ToArray();
            if (all.Length == 0)
                return;
            page.Append($"\n## {heading}\n\n```csharp\n");
            foreach (string line in all)
                page.Append(line).Append('\n');
            page.Append("```\n");
        }

        private void TypeTable(StringBuilder page, string heading, string folder, IEnumerable<ReferenceType> types)
        {
            ReferenceType[] all = types.ToArray();
            if (all.Length == 0)
                return;
            page.Append($"\n## {heading}\n\n| Type | Summary |\n|---|---|\n");
            foreach (ReferenceType type in all)
                page.Append($"| {Link(folder, type)} | {Cell(type.Summary)} |\n");
        }

        private string TypeLink(string folder, Type type) =>
            _pages.TryGetValue(Definition(type), out ReferenceType page)
                ? $"[`{TypeNames.Display(type)}`]({Relative(folder, page.PagePath)})"
                : $"`{TypeNames.Display(type)}`";

        private static string Link(string folder, ReferenceType type) =>
            $"[`{type.Key}`]({Relative(folder, type.PagePath)})";

        private static string Relative(string folder, string path) =>
            Path.GetRelativePath(folder, path).Replace('\\', '/');

        private static string GuideLink(ReferencePackage package, string up) =>
            File.Exists(Path.Combine(package.Root, "documentation.md")) ? $" · [Usage guide]({up}documentation.md)" : "";

        private static string Title(string key) => key.Contains('<') ? $"`{key}`" : key;

        private static string Cell(string text) => text.Replace("|", "\\|");

        public static Type Definition(Type type) => type.IsGenericType ? type.GetGenericTypeDefinition() : type;

        public static string Slug(string heading) =>
            new string(heading.ToLowerInvariant().Where(c => char.IsLetterOrDigit(c) || c is '-' or '_' or ' ').ToArray()).Replace(' ', '-');
    }
}
